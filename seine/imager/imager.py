# squashfs/erofs are not g.mkfs() targets, so RO_FSTYPES mounts are
# staged as this and replaced later (see create()'s finalize pass).
STAGING_TYPE = "ext4"

# Fixed, so the same spec always derives the same GPT/filesystem UUIDs.
UUID_NAMESPACE = uuid.uuid5(uuid.NAMESPACE_DNS, "seine.debian.org")

# Fallback hypervisor per arch, used when cross-building and 'imager:
# hypervisor:' is unset (guestfs would otherwise launch its host-arch qemu).
DEFAULT_HYPERVISORS = {
    "amd64": "/usr/bin/qemu-system-x86_64",
    "arm64": "/usr/bin/qemu-system-aarch64",
    "armhf": "/usr/bin/qemu-system-arm",
    "i386":  "/usr/bin/qemu-system-i386",
}

# libguestfs hardcodes x86-only qemu flags (machine, cpu, console) for any
# hypervisor, with no override for some of them. Confirmed for arm64 only,
# via a real cross-arch build.
CROSS_ARCH_QEMU_FIXUPS = {
    "arm64": {"machine": "virt,accel=tcg", "cpu": "max", "console": "ttyAMA0"},
}

QEMU_WRAPPER_SCRIPT = """#!/bin/bash
# generated by seine -- fixes up qemu flags libguestfs hardcodes for
# x86, then execs the real hypervisor.
args=()
while [ $# -gt 0 ]; do
    case "$1" in
        -global)
            if [ "$2" = "virtio-blk-pci.scsi=off" ]; then
                shift 2
                continue
            fi
            ;;
        -machine)
            args+=("-machine" "{machine}")
            shift 2
            continue
            ;;
        -cpu)
            args+=("-cpu" "{cpu}")
            shift 2
            continue
            ;;
        -append)
            args+=("-append" "${{2/console=ttyS0/console={console}}}")
            shift 2
            continue
            ;;
    esac
    args+=("$1")
    shift
done
exec "{real_hv}" "${{args[@]}}"
"""

